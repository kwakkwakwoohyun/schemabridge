_COLUMNS = ("pay_dt", "payee_nm", "payee_biz_no", "pay_amt", "wht_tax_amt", "income_type_cd")
_NUMERIC_COLUMNS = {"pay_amt", "wht_tax_amt"}


def ensure_demo_db(path: str = DB_PATH) -> str:
    if os.path.exists(path):
        return path

    columns_ddl = ", ".join(f"{c} {'NUMERIC' if c in _NUMERIC_COLUMNS else 'TEXT'}" for c in _COLUMNS)
    placeholders = ", ".join("?" for _ in _COLUMNS)

    conn = sqlite3.connect(path)
    try:
        for table, rows in _ROWS_BY_TABLE.items():
            conn.execute(f"CREATE TABLE {table} ({columns_ddl})")
            conn.executemany(f"INSERT INTO {table} VALUES ({placeholders})", rows)
        conn.commit()
    finally:
        conn.close()

    return path


if __name__ == "__main__":
    db_path = ensure_demo_db()
    conn = sqlite3.connect(db_path)
    for table in _ROWS_BY_TABLE:
        count = conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        print(f"{table}: {count}건")
    conn.close()
    print(f"준비 완료: {db_path}")
